describe('frases de comidas de verdad', () => {
  it('hay muchas', () => {
    expect(PHRASES.length).toBeGreaterThan(200);
    expect(PHRASES_V2.length).toBeGreaterThan(200);
    expect(new Set([...PHRASES, ...PHRASES_V2]).size).toBe(PHRASES.length + PHRASES_V2.length);
  });

  it.each([...PHRASES, ...PHRASES_V2])('%s', (phrase) => {
    const analysis = analyzeMealText(phrase, table);
    expect(analysis.items.length, 'ningún alimento reconocido').toBeGreaterThan(0);
    expect(analysis.unknown, 'palabras sin entender').toEqual([]);
    const kcal = analysis.items.reduce((sum, item) => sum + item.kcal, 0);
    // Una comida de verdad: sin disparates (nada de miles de calorías por un error de lectura).
    expect(kcal).toBeLessThan(3_500);
    // Cada plato compuesto suma sus piezas.
    for (const item of analysis.items) {
      if (item.parts === undefined) continue;
      expect(Math.abs(item.parts.reduce((sum, part) => sum + part.kcal, 0) - item.kcal), 'las piezas no suman el plato').toBeLessThanOrEqual(item.parts.length);
    }
  });
});
